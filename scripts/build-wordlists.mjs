#!/usr/bin/env node
/**
 * Regenerates src/game/words/answers.ts and src/game/words/allowed.ts.
 *
 * Sources (downloaded into .cache/wordlists on first run):
 *  - ENABLE2K word list (public domain): the base dictionary of valid guesses.
 *  - SCOWL (Spell Checker Oriented Word Lists): levels <= 50 mark "common" words and
 *    exclude proper nouns; levels <= 70 add some newer words to the allowed list.
 *  - FrequencyWords en_50k (OpenSubtitles frequencies): used to rank answer candidates.
 *
 * NOTE: the daily puzzle picks an index into the answers list, so changing the answer
 * list changes every past and future daily answer. Regenerate before launch, not after.
 *
 * Usage: node scripts/build-wordlists.mjs [answerCount=2300]
 */
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const CACHE = path.join(ROOT, '.cache', 'wordlists');
const OUT = path.join(ROOT, 'src', 'game', 'words');
const ANSWER_TARGET = Number(process.argv[2] ?? 2300);

const SOURCES = {
  'enable1.txt': 'https://raw.githubusercontent.com/dolph/dictionary/master/enable1.txt',
  'freq.txt': 'https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/en/en_50k.txt',
  'scowl.tar.gz': 'https://downloads.sourceforge.net/wordlist/scowl-2020.12.07.tar.gz',
};

// Words that are valid guesses but shouldn't be daily answers (offensive, crude, or name-like).
const ANSWER_BLOCKLIST = new Set(
  `bitch whore sluts pussy dicks dildo penis twats cunts cocks boner horny porno pimps rapes raped
   bosom boobs titty kinky nazis wanks homos queer dykes gooks spics kikes chink paddy retard negro
   semen sperm anals bongs sexed sexes alamo rouen perry vichy aggie wilco youse ganja hussy aline
   levin senna willy matey actin aargh gonif lotsa nosed dopey enema grope`.split(/\s+/),
);

const FIVE = /^[a-z]{5}$/;

function ensureSources() {
  fs.mkdirSync(CACHE, { recursive: true });
  for (const [file, url] of Object.entries(SOURCES)) {
    const dest = path.join(CACHE, file);
    if (!fs.existsSync(dest) || fs.statSync(dest).size === 0) {
      console.log(`Downloading ${url}`);
      execSync(`curl -fsSL -o "${dest}" "${url}"`, { stdio: 'inherit' });
    }
  }
  const scowlDir = path.join(CACHE, 'scowl-2020.12.07');
  if (!fs.existsSync(scowlDir)) execSync(`tar xzf scowl.tar.gz`, { cwd: CACHE });
  return path.join(scowlDir, 'final');
}

function readLines(file, encoding = 'utf8') {
  return fs.readFileSync(file, encoding).split(/\r?\n/);
}

function readScowl(dir, maxLevel) {
  const words = new Set();
  for (const f of fs.readdirSync(dir)) {
    const m = /^(english|american)-words\.(\d+)$/.exec(f);
    if (m && Number(m[2]) <= maxLevel) {
      for (const w of readLines(path.join(dir, f), 'latin1')) words.add(w);
    }
  }
  return words;
}

const scowlDir = ensureSources();
const dictionary = new Set(readLines(path.join(CACHE, 'enable1.txt')));
const common = readScowl(scowlDir, 50);
for (const w of readScowl(scowlDir, 70)) if (FIVE.test(w)) dictionary.add(w);

const isInflection = (w) =>
  // plurals / 3rd-person verbs ("cakes", "jumps") but not "grass", "bonus", "basis"
  (/[^s]s$/.test(w) && !/(us|is)$/.test(w)) ||
  // past tenses whose stem is also a word ("acted", "moved", "tried")
  (/ed$/.test(w) && (dictionary.has(w.slice(0, -2)) || dictionary.has(w.slice(0, -1)) || /ied$/.test(w)));

const answers = [];
for (const line of readLines(path.join(CACHE, 'freq.txt'))) {
  const w = line.split(' ')[0];
  if (!FIVE.test(w) || !dictionary.has(w) || !common.has(w)) continue;
  if (ANSWER_BLOCKLIST.has(w) || isInflection(w) || answers.includes(w)) continue;
  answers.push(w);
  if (answers.length >= ANSWER_TARGET) break;
}
answers.sort();

const answerSet = new Set(answers);
const allowed = [...dictionary].filter((w) => FIVE.test(w) && !answerSet.has(w)).sort();

function writeList(file, name, doc, words) {
  // One space-separated string per initial letter keeps the file compact and diff-friendly.
  const byLetter = new Map();
  for (const w of words) byLetter.set(w[0], [...(byLetter.get(w[0]) ?? []), w]);
  const body = [...byLetter.values()].map((ws) => `  '${ws.join(' ')}',`).join('\n');
  const src = `// Generated by scripts/build-wordlists.mjs — do not edit by hand.\n/** ${doc} */\nexport const ${name}: readonly string[] = [\n${body}\n].join(' ').split(' ');\n`;
  fs.writeFileSync(path.join(OUT, file), src);
}

fs.mkdirSync(OUT, { recursive: true });
writeList('answers.ts', 'ANSWERS', `${answers.length} candidate solutions (common words, no plurals/past tenses).`, answers);
writeList('allowed.ts', 'ALLOWED_GUESSES', `${allowed.length} additional valid guesses (not solutions).`, allowed);
console.log(`answers: ${answers.length}, extra allowed guesses: ${allowed.length}`);
